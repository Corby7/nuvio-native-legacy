// Up to how many bytes the frequency guess looks at, as in the web app.
#define SAMPLE 4096

static int isValidUtf8(const unsigned char *s, long n) {
  long i = 0;
  while (i < n) {
    unsigned char c = s[i++];
    int more;
    if (c <= 0x7f) continue;
    if (c >= 0xc2 && c <= 0xdf) more = 1;
    else if (c >= 0xe0 && c <= 0xef) more = 2;
    else if (c >= 0xf0 && c <= 0xf4) more = 3;
    else return 0;
    if (i + more > n) return 0;
    while (more--) if ((s[i++] & 0xc0) != 0x80) return 0;
  }
  return 1;
}

// The part of a language code before '-' or '_', lower case, into `dst`.
static void languageBase(const char *language, char *dst, size_t size) {
  size_t i = 0;
  if (!language) language = "";
  while (language[i] && language[i] != '-' && language[i] != '_' && i + 1 < size) {
    char c = language[i];
    dst[i++] = (char)(c >= 'A' && c <= 'Z' ? c + 32 : c);
  }
  dst[i] = 0;
}

static int among(const char *base, const char *const *list) {
  for (; *list; list++) if (!strcmp(base, *list)) return 1;
  return 0;
}

// The codepage a language is usually written in, -1 when the language says
// nothing, CP_UNSUPPORTED for the CJK languages.
static int fromLanguage(const char *base) {
  static const char *const western[] = {
    "por", "pt", "pob", "spa", "es", "fra", "fre", "fr", "deu", "ger", "de", "ita",
    "it", "nld", "dut", "nl", "eng", "en", "dan", "da", "swe", "sv", "nor", "no",
    "fin", "fi", "cat", "ca", "glg", "gl", "eus", "baq", "eu", NULL };
  static const char *const cyrillic[] = {
    "rus", "ru", "ukr", "uk", "bel", "be", "bul", "bg", "mkd", "mk", "srp", "sr",
    NULL };
  static const char *const central[] = {
    "pol", "pl", "ces", "cs", "cze", "hun", "hu", "slv", "sl", "hrv", "hr", "ron",
    "ro", "rum", "slk", "sk", NULL };
  static const char *const cjk[] = {
    "zho", "zh", "chi", "jpn", "ja", "kor", "ko", NULL };
  static const char *const hebrew[] = { "heb", "he", "iw", NULL };
  static const char *const arabic[] = { "ara", "ar", NULL };
  static const char *const greek[] = { "ell", "el", "gre", NULL };
  static const char *const turkish[] = { "tur", "tr", NULL };
  static const char *const thai[] = { "tha", "th", NULL };
  static const char *const vietnamese[] = { "vie", "vi", NULL };
  if (!*base) return -1;
  if (among(base, western)) return CP_1252;
  if (among(base, cyrillic)) return CP_1251;
  if (among(base, central)) return CP_1250;
  if (among(base, hebrew)) return CP_1255;
  if (among(base, arabic)) return CP_1256;
  if (among(base, greek)) return CP_1253;
  if (among(base, turkish)) return CP_1254;
  if (among(base, thai)) return CP_874;
  if (among(base, vietnamese)) return CP_1258;
  if (among(base, cjk)) return CP_UNSUPPORTED;
  return -1;
}

static int oneOf(unsigned char c, const unsigned char *set, size_t n) {
  return memchr(set, c, n) != NULL;
}

// The web app's byte-frequency guess (detectUniversalCharset), for when the
// language says nothing. Its CJK branches decode the sample to score it, which
// needs the multibyte tables this module does not carry; only the Shift_JIS
// hiragana signature survives, to refuse such a file rather than garble it.
static int guess(const unsigned char *s, long n) {
  long first = 0, i, start;
  int letters = 0, high = 0, run = 0, longest = 0, hiragana = 0;
  int thai = 0, hebrew = 0, arabicAl = 0, russian = 0, koi8 = 0, greek = 0, c0df = 0;
  int turkish = 0, centralEu = 0, vietnamese = 0;
  static const unsigned char TR[] = { 0xf0, 0xfe, 0xfd, 0xd0, 0xde, 0xdd };
  static const unsigned char CE[] = { 0xb9, 0xb3, 0x9c, 0x9f, 0x9a, 0x9e, 0x8c, 0x8f,
                                      0x8a, 0x8e, 0x8d, 0x9d, 0xcf, 0xef, 0xbe };
  static const unsigned char VI[] = { 0xcc, 0xd2, 0xf2, 0xf5 };
  static const unsigned char RU[] = { 0xee, 0xe0, 0xe5, 0xe8, 0xff, 0xfb, 0xf3, 0xfd, 0xfe };
  static const unsigned char KO[] = { 0xcf, 0xc1, 0xc5, 0xc9, 0xd5, 0xdf };
  static const unsigned char EL[] = { 0xe1, 0xef, 0xe5, 0xe7, 0xfd, 0xfe, 0xe9, 0xf5,
                                      0xf9, 0xdc, 0xdd, 0xde, 0xdf, 0xfa, 0xfb, 0xfc };
  while (first < n && s[first] < 0x80) first++;
  if (first >= n) return CP_UTF8;
  start = first > 100 ? first - 100 : 0;
  s += start; n -= start;
  if (n > SAMPLE) n = SAMPLE;
  for (i = 0; i < n; i++) {
    unsigned char c = s[i];
    if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')) { letters++; run = 0; }
    else if (c >= 0x80) { high++; if (++run > longest) longest = run; }
    else run = 0;
    if (i + 1 < n && c == 0x82 && s[i + 1] >= 0x9f && s[i + 1] <= 0xf1) hiragana++;
  }
  if (hiragana >= 2) return CP_UNSUPPORTED;
  for (i = 0; i < n; i++) {
    unsigned char c = s[i];
    if (oneOf(c, TR, sizeof TR)) turkish++;
    if (oneOf(c, CE, sizeof CE)) centralEu++;
    if (oneOf(c, VI, sizeof VI)) vietnamese++;
  }
  // Mostly Latin text with scattered accents: a Latin codepage.
  if (letters >= high || longest <= 2) {
    if (turkish >= 2 && turkish > centralEu) return CP_1254;
    if (centralEu >= 2 && centralEu >= vietnamese) return CP_1250;
    if (vietnamese >= 2) return CP_1258;
    return CP_1252;
  }
  for (i = 0; i < n; i++) {
    unsigned char c = s[i];
    if (c >= 0xa1 && c <= 0xbf) thai++;
    if (c >= 0xe0 && c <= 0xfa) hebrew++;
    if (c >= 0xc0 && c <= 0xdf) c0df++;
    if (oneOf(c, RU, sizeof RU)) russian++;
    if (oneOf(c, KO, sizeof KO)) koi8++;
    if (oneOf(c, EL, sizeof EL)) greek++;
    if (c == 0xc7 && i + 1 < n && s[i + 1] == 0xe1) arabicAl++;   // "ال"
  }
  if (hebrew == high && hebrew >= 4 && c0df == 0) return CP_1255;
  if (thai >= 4 && thai * 4 >= high) return CP_874;
  if (arabicAl > 0) return CP_1256;
  if (koi8 > russian && koi8 >= 3) return CP_KOI8R;
  if (russian > greek && russian >= 4) return CP_1251;
  if (greek > russian && greek >= 4) return CP_1253;
  return CP_1252;
}

static size_t putUtf8(char *w, unsigned cp) {
  if (cp < 0x80) { w[0] = (char)cp; return 1; }
  if (cp < 0x800) { w[0] = (char)(0xc0 | cp >> 6); w[1] = (char)(0x80 | (cp & 0x3f)); return 2; }
  if (cp < 0x10000) {
    w[0] = (char)(0xe0 | cp >> 12); w[1] = (char)(0x80 | ((cp >> 6) & 0x3f));
    w[2] = (char)(0x80 | (cp & 0x3f)); return 3;
  }
  w[0] = (char)(0xf0 | cp >> 18); w[1] = (char)(0x80 | ((cp >> 12) & 0x3f));
  w[2] = (char)(0x80 | ((cp >> 6) & 0x3f)); w[3] = (char)(0x80 | (cp & 0x3f)); return 4;
}

// A byte the codepage leaves undefined becomes '?': U+FFFD would draw as a box
// in most of the TV's faces.
static char *fromSingleByte(const unsigned char *s, long n, int cp) {
  char *out = malloc((size_t)n * 3 + 1), *w = out;
  long i;
  if (!out) return NULL;
  for (i = 0; i < n; i++) {
    unsigned c = s[i];
    if (c >= 0x80) c = HIGH[cp][c - 0x80] ? HIGH[cp][c - 0x80] : '?';
    w += putUtf8(w, c);
  }
  *w = 0;
  return out;
}

static char *fromUtf16(const unsigned char *s, long n, int bigEndian) {
  char *out = malloc((size_t)(n / 2) * 3 + 1), *w = out;
  long i;
  if (!out) return NULL;
  for (i = 0; i + 1 < n; i += 2) {
    unsigned u = bigEndian ? (unsigned)(s[i] << 8 | s[i + 1]) : (unsigned)(s[i + 1] << 8 | s[i]);
    if (u >= 0xd800 && u <= 0xdbff && i + 3 < n) {
      unsigned lo = bigEndian ? (unsigned)(s[i + 2] << 8 | s[i + 3])
                              : (unsigned)(s[i + 3] << 8 | s[i + 2]);
      if (lo >= 0xdc00 && lo <= 0xdfff) {
        u = 0x10000 + ((u - 0xd800) << 10) + (lo - 0xdc00);
        i += 2;
      } else u = '?';
    } else if (u >= 0xd800 && u <= 0xdfff) u = '?';
    if (u) w += putUtf8(w, u);   // a NUL would end the string early
  }
  *w = 0;
  return out;
}

// Decodes the next code point of valid UTF-8 and advances *p.
static unsigned nextUtf8(const unsigned char **p) {
  const unsigned char *s = *p;
  unsigned cp;
  if (s[0] < 0x80) { *p += 1; return s[0]; }
  if (s[0] < 0xe0) { *p += 2; return (unsigned)(s[0] & 0x1f) << 6 | (s[1] & 0x3f); }
  if (s[0] < 0xf0) {
    *p += 3;
    return (unsigned)(s[0] & 0x0f) << 12 | (unsigned)(s[1] & 0x3f) << 6 | (s[2] & 0x3f);
  }
  cp = (unsigned)(s[0] & 0x07) << 18 | (unsigned)(s[1] & 0x3f) << 12 |
       (unsigned)(s[2] & 0x3f) << 6 | (s[3] & 0x3f);
  *p += 4;
  return cp;
}

static int inScript(unsigned cp, int cp_) {
  switch (cp_) {
    case CP_1255: return cp >= 0x0590 && cp <= 0x05ff;
    case CP_1256: return cp >= 0x0600 && cp <= 0x06ff;
    case CP_1253: return cp >= 0x0370 && cp <= 0x03ff;
    default:      return cp >= 0x0400 && cp <= 0x04ff;
  }
}

// DOUBLE-ENCODED TEXT: valid UTF-8 whose letters are a legacy codepage's bytes
// read as Latin-1 ("àìä" where Hebrew belongs). It happens when a site converts
// a Windows-1255 file to UTF-8 assuming it was Latin-1, and it is common enough
// that the web app repairs it (repairDoubleEncodedUtf8IfNeeded). The repair
// turns every code point back into its byte and decodes those bytes again. With
// a Hebrew, Arabic, Greek or Russian hint it is tried on the hint's codepage;
// with no hint only Hebrew is guessed, the case seen in the wild.
static char *repairDoubleEncoded(char *text, const char *base) {
  static const char *const he[] = { "heb", "he", "iw", NULL };
  static const char *const ar[] = { "ara", "ar", NULL };
  static const char *const el[] = { "ell", "el", "gre", NULL };
  static const char *const ru[] = { "rus", "ru", "ukr", "uk", NULL };
  int hinted, target = among(base, he) ? CP_1255 : among(base, ar) ? CP_1256
             : among(base, el) ? CP_1253 : among(base, ru) ? CP_1251 : -1;
  const unsigned char *p = (const unsigned char *)text;
  size_t n = strlen(text), k = 0;
  unsigned char *bytes;
  int latin = 0, words = 0, mojibakeWords = 0, wordLen = 0, wordBad = 0, found = 0;
  char *fixed;
  hinted = target >= 0;
  if (!n || !(bytes = malloc(n))) return text;
  while (*p) {
    unsigned cp = nextUtf8(&p);
    if (cp > 0xff) { free(bytes); return text; }
    bytes[k++] = (unsigned char)cp;
    if (cp >= 0xe0 && cp <= 0xfa) latin++;
    // A mojibake word is made only of U+00E0..U+00FA and punctuation.
    if (cp == ' ' || cp == '\t' || cp == '\n' || cp == '\r') {
      if (wordLen >= 2) { words++; if (!wordBad) mojibakeWords++; }
      wordLen = wordBad = 0;
    } else {
      wordLen++;
      if (!(cp >= 0xe0 && cp <= 0xfa) && !strchr("<i>/,.!?:'\"\\_()-", (int)cp)) wordBad = 1;
    }
  }
  if (wordLen >= 2) { words++; if (!wordBad) mojibakeWords++; }
  if (hinted ? latin < 5 : (mojibakeWords < 5 || mojibakeWords * 3 < words)) {
    free(bytes); return text;
  }
  if (target < 0) target = CP_1255;
  fixed = fromSingleByte(bytes, (long)k, target);
  free(bytes);
  if (!fixed) return text;
  for (p = (const unsigned char *)fixed; *p;) if (inScript(nextUtf8(&p), target)) found++;
  if (found >= (hinted ? 1 : 10)) {
    free(text); return fixed;
  }
  free(fixed);
  return text;
}

char *subcharset_utf8(const char *bytes, long n, const char *language,
                      const char **charset) {
  const unsigned char *s = (const unsigned char *)bytes;
  char base[8], *out;
  int cp;
  if (charset) *charset = "";
  if (!bytes || n <= 0) return NULL;
  languageBase(language, base, sizeof base);
  if (n >= 2 && s[0] == 0xff && s[1] == 0xfe) {
    if (charset) *charset = "utf-16le";
    return fromUtf16(s + 2, n - 2, 0);
  }
  if (n >= 2 && s[0] == 0xfe && s[1] == 0xff) {
    if (charset) *charset = "utf-16be";
    return fromUtf16(s + 2, n - 2, 1);
  }
  if (n >= 3 && s[0] == 0xef && s[1] == 0xbb && s[2] == 0xbf) { s += 3; n -= 3; }
  if (isValidUtf8(s, n)) {
    if (!(out = malloc((size_t)n + 1))) return NULL;
    memcpy(out, s, (size_t)n); out[n] = 0;
    if (charset) *charset = "utf-8";
    return repairDoubleEncoded(out, base);
  }
  cp = fromLanguage(base);
  if (cp < 0) cp = guess(s, n);
  if (cp == CP_UNSUPPORTED || cp == CP_UTF8 || cp >= CP_N) {
    if (charset) *charset = "unsupported";
    return NULL;
  }
  if (charset) *charset = NAMES[cp];
  out = fromSingleByte(s, n, cp);
  return out ? repairDoubleEncoded(out, base) : NULL;
}
